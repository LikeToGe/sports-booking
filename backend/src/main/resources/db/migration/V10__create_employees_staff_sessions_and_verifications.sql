CREATE TABLE venue_employee (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    employee_no VARCHAR(40) NOT NULL COMMENT '店员工号',
    organization_id BIGINT UNSIGNED NOT NULL COMMENT '经营主体ID',
    store_id BIGINT UNSIGNED NOT NULL COMMENT '门店ID',
    employee_name VARCHAR(64) NOT NULL COMMENT '店员姓名',
    employee_status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、DISABLED',
    disabled_at DATETIME NULL COMMENT '停用UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_venue_employee_no (employee_no),
    KEY idx_venue_employee_store_status (store_id, employee_status),
    CONSTRAINT fk_venue_employee_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_venue_employee_store FOREIGN KEY (store_id) REFERENCES store (id),
    CHECK (employee_status IN ('ACTIVE', 'DISABLED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='场馆店员';

CREATE TABLE employee_binding_code (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    employee_id BIGINT UNSIGNED NOT NULL COMMENT '店员ID',
    code_hash CHAR(64) NOT NULL COMMENT '一次性绑定码哈希',
    code_status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、USED、REVOKED、EXPIRED',
    expires_at DATETIME NOT NULL COMMENT '到期UTC时间',
    used_at DATETIME NULL COMMENT '使用UTC时间',
    issued_by_account_id BIGINT UNSIGNED NOT NULL COMMENT '签发场馆管理员ID',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_employee_binding_code_hash (code_hash),
    KEY idx_employee_binding_code_employee_status (employee_id, code_status, expires_at),
    CONSTRAINT fk_employee_binding_code_employee FOREIGN KEY (employee_id) REFERENCES venue_employee (id),
    CHECK (code_status IN ('ACTIVE', 'USED', 'REVOKED', 'EXPIRED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='店员一次性绑定码';

CREATE TABLE employee_wechat_binding (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    employee_id BIGINT UNSIGNED NOT NULL COMMENT '店员ID',
    provider VARCHAR(24) NOT NULL COMMENT '身份提供方：MOCK_WECHAT',
    provider_subject_hash CHAR(64) NOT NULL COMMENT '提供方身份哈希',
    binding_status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、REVOKED',
    active_employee_key BIGINT UNSIGNED NULL COMMENT '活动绑定时等于employee_id',
    active_subject_key CHAR(64) NULL COMMENT '活动绑定时等于身份哈希',
    bound_at DATETIME NOT NULL COMMENT '绑定UTC时间',
    revoked_at DATETIME NULL COMMENT '撤销UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_employee_wechat_active_employee (active_employee_key),
    UNIQUE KEY uk_employee_wechat_active_subject (active_subject_key),
    KEY idx_employee_wechat_binding_employee (employee_id, binding_status),
    CONSTRAINT fk_employee_wechat_binding_employee FOREIGN KEY (employee_id) REFERENCES venue_employee (id),
    CHECK (provider = 'MOCK_WECHAT'),
    CHECK (binding_status IN ('ACTIVE', 'REVOKED')),
    CHECK ((binding_status = 'ACTIVE' AND active_employee_key IS NOT NULL AND active_subject_key IS NOT NULL) OR
           (binding_status = 'REVOKED' AND active_employee_key IS NULL AND active_subject_key IS NULL)),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='店员微信绑定历史';

CREATE TABLE staff_session (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    employee_id BIGINT UNSIGNED NOT NULL COMMENT '店员ID',
    employee_wechat_binding_id BIGINT UNSIGNED NOT NULL COMMENT '微信绑定ID',
    access_token_hash CHAR(64) NOT NULL COMMENT '访问令牌哈希',
    refresh_token_hash CHAR(64) NOT NULL COMMENT '刷新令牌哈希',
    access_expires_at DATETIME NOT NULL COMMENT '访问令牌到期UTC时间',
    refresh_expires_at DATETIME NOT NULL COMMENT '刷新令牌到期UTC时间',
    revoked_at DATETIME NULL COMMENT '撤销UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_staff_session_access_hash (access_token_hash),
    UNIQUE KEY uk_staff_session_refresh_hash (refresh_token_hash),
    KEY idx_staff_session_employee_active (employee_id, revoked_at, access_expires_at),
    CONSTRAINT fk_staff_session_employee FOREIGN KEY (employee_id) REFERENCES venue_employee (id),
    CONSTRAINT fk_staff_session_binding FOREIGN KEY (employee_wechat_binding_id) REFERENCES employee_wechat_binding (id),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='店员小程序会话';

CREATE TABLE booking_verification_credential (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    booking_order_id BIGINT UNSIGNED NOT NULL COMMENT '预约订单ID',
    store_id BIGINT UNSIGNED NOT NULL COMMENT '门店ID',
    credential_type VARCHAR(16) NOT NULL COMMENT '凭证类型：QR、SHORT_CODE',
    token_hash CHAR(64) NULL COMMENT '二维码令牌哈希',
    short_code_hash CHAR(64) NULL COMMENT '短码用途哈希',
    active_short_code_hash CHAR(64) NULL COMMENT '活动短码用途哈希',
    credential_status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、USED、REVOKED、EXPIRED',
    valid_from DATETIME NOT NULL COMMENT '开始核销UTC时间',
    valid_to DATETIME NOT NULL COMMENT '结束核销UTC时间',
    used_by_employee_id BIGINT UNSIGNED NULL COMMENT '核销店员ID',
    used_at DATETIME NULL COMMENT '使用UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_verification_credential_token_hash (token_hash),
    UNIQUE KEY uk_verification_credential_store_active_short_code (store_id, active_short_code_hash),
    KEY idx_verification_credential_order_status (booking_order_id, credential_status),
    CONSTRAINT fk_verification_credential_order FOREIGN KEY (booking_order_id) REFERENCES booking_order (id),
    CONSTRAINT fk_verification_credential_store FOREIGN KEY (store_id) REFERENCES store (id),
    CONSTRAINT fk_verification_credential_employee FOREIGN KEY (used_by_employee_id) REFERENCES venue_employee (id),
    CHECK (credential_type IN ('QR', 'SHORT_CODE')),
    CHECK ((credential_type = 'QR' AND token_hash IS NOT NULL AND short_code_hash IS NULL) OR
           (credential_type = 'SHORT_CODE' AND token_hash IS NULL AND short_code_hash IS NOT NULL)),
    CHECK ((credential_status = 'ACTIVE' AND ((credential_type = 'QR' AND active_short_code_hash IS NULL) OR
           (credential_type = 'SHORT_CODE' AND active_short_code_hash IS NOT NULL))) OR credential_status <> 'ACTIVE'),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='订单核销凭证';

CREATE TABLE booking_verification (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    booking_order_id BIGINT UNSIGNED NOT NULL COMMENT '预约订单ID',
    employee_id BIGINT UNSIGNED NOT NULL COMMENT '首次成功核销店员ID',
    credential_id BIGINT UNSIGNED NOT NULL COMMENT '使用凭证ID',
    verification_method VARCHAR(16) NOT NULL COMMENT '核销方式：QR、SHORT_CODE',
    verified_at DATETIME NOT NULL COMMENT '核销UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_booking_verification_order (booking_order_id),
    CONSTRAINT fk_booking_verification_order FOREIGN KEY (booking_order_id) REFERENCES booking_order (id),
    CONSTRAINT fk_booking_verification_employee FOREIGN KEY (employee_id) REFERENCES venue_employee (id),
    CONSTRAINT fk_booking_verification_credential FOREIGN KEY (credential_id) REFERENCES booking_verification_credential (id),
    CHECK (verification_method IN ('QR', 'SHORT_CODE')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='预约首次核销事实';

CREATE TABLE verification_attempt (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    employee_id BIGINT UNSIGNED NOT NULL COMMENT '尝试店员ID',
    booking_order_id BIGINT UNSIGNED NULL COMMENT '预约订单ID',
    credential_id BIGINT UNSIGNED NULL COMMENT '凭证ID',
    verification_method VARCHAR(16) NOT NULL COMMENT '核销方式：QR、SHORT_CODE',
    attempt_result VARCHAR(16) NOT NULL COMMENT '结果：SUCCEEDED、DUPLICATE、REJECTED',
    failure_reason VARCHAR(64) NULL COMMENT '失败原因编码',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    KEY idx_verification_attempt_employee_time (employee_id, gmt_created_time),
    KEY idx_verification_attempt_order_time (booking_order_id, gmt_created_time),
    CONSTRAINT fk_verification_attempt_employee FOREIGN KEY (employee_id) REFERENCES venue_employee (id),
    CONSTRAINT fk_verification_attempt_order FOREIGN KEY (booking_order_id) REFERENCES booking_order (id),
    CONSTRAINT fk_verification_attempt_credential FOREIGN KEY (credential_id) REFERENCES booking_verification_credential (id),
    CHECK (verification_method IN ('QR', 'SHORT_CODE')),
    CHECK (attempt_result IN ('SUCCEEDED', 'DUPLICATE', 'REJECTED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='核销尝试审计';
