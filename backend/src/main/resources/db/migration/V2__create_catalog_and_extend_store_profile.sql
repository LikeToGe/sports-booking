CREATE TABLE sport_category (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    parent_id BIGINT UNSIGNED NULL COMMENT '父分类ID，一级分类为空',
    code VARCHAR(32) NOT NULL COMMENT '分类编码',
    name VARCHAR(64) NOT NULL COMMENT '分类名称',
    level TINYINT UNSIGNED NOT NULL COMMENT '层级：1一级 2二级',
    icon VARCHAR(64) NULL COMMENT '图标标识',
    sort_order INT UNSIGNED NOT NULL DEFAULT '0' COMMENT '排序值，越小越靠前',
    status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、DISABLED',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_sport_category_code (code),
    KEY idx_sport_category_parent_sort (parent_id, sort_order, id),
    KEY idx_sport_category_status (status),
    CONSTRAINT fk_sport_category_parent FOREIGN KEY (parent_id) REFERENCES sport_category (id),
    CHECK (level IN (1, 2)),
    CHECK (status IN ('ACTIVE', 'DISABLED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='运动分类';

CREATE TABLE rental_type (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    sport_category_id BIGINT UNSIGNED NOT NULL COMMENT '具体运动项目分类ID',
    name VARCHAR(64) NOT NULL COMMENT '出租类型名称',
    status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、DISABLED',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_rental_type_category_name (sport_category_id, name),
    KEY idx_rental_type_status (status),
    CONSTRAINT fk_rental_type_sport_category FOREIGN KEY (sport_category_id) REFERENCES sport_category (id),
    CHECK (status IN ('ACTIVE', 'DISABLED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='出租类型';

