CREATE TABLE booking_cancellation (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    booking_order_id BIGINT UNSIGNED NOT NULL COMMENT '预约订单ID',
    cancellation_type VARCHAR(24) NOT NULL COMMENT '取消类型：USER、VENUE、PAYMENT_FAILED、PAYMENT_EXPIRED',
    reason VARCHAR(255) NOT NULL COMMENT '取消原因',
    cancelled_by_type VARCHAR(24) NOT NULL COMMENT '发起方：MINI_USER、VENUE_ADMIN、SYSTEM',
    cancelled_by_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '发起方ID',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_booking_cancellation_order (booking_order_id),
    CONSTRAINT fk_booking_cancellation_order FOREIGN KEY (booking_order_id) REFERENCES booking_order (id),
    CHECK (cancellation_type IN ('USER', 'VENUE', 'PAYMENT_FAILED', 'PAYMENT_EXPIRED')),
    CHECK (cancelled_by_type IN ('MINI_USER', 'VENUE_ADMIN', 'SYSTEM')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='预约取消事实';

CREATE TABLE refund_order (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    refund_no VARCHAR(40) NOT NULL COMMENT '退款业务编号',
    booking_order_id BIGINT UNSIGNED NOT NULL COMMENT '预约订单ID',
    payment_order_id BIGINT UNSIGNED NOT NULL COMMENT '原支付单ID',
    refund_source_type VARCHAR(24) NOT NULL COMMENT '退款来源：USER_CANCEL、VENUE_CANCEL、LATE_PAYMENT',
    refund_source_id BIGINT UNSIGNED NOT NULL COMMENT '来源业务ID',
    refund_scope VARCHAR(16) NOT NULL COMMENT '退款范围：FULL',
    amount_fen INT UNSIGNED NOT NULL COMMENT '退款金额分',
    currency VARCHAR(8) NOT NULL COMMENT '币种',
    refund_status VARCHAR(24) NOT NULL COMMENT '退款状态',
    provider_refund_no VARCHAR(64) NULL COMMENT 'Provider退款单号',
    provider_status VARCHAR(32) NULL COMMENT 'Provider原始状态',
    provider_result_at DATETIME NULL COMMENT 'Provider结果UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_refund_order_no (refund_no),
    UNIQUE KEY uk_refund_source_scope (refund_source_type, refund_source_id, refund_scope),
    KEY idx_refund_order_booking_status (booking_order_id, refund_status),
    CONSTRAINT fk_refund_order_booking FOREIGN KEY (booking_order_id) REFERENCES booking_order (id),
    CONSTRAINT fk_refund_order_payment FOREIGN KEY (payment_order_id) REFERENCES payment_order (id),
    CHECK (refund_source_type IN ('USER_CANCEL', 'VENUE_CANCEL', 'LATE_PAYMENT')),
    CHECK (refund_scope = 'FULL'),
    CHECK (refund_status IN ('REFUND_PENDING', 'REFUND_PROCESSING', 'REFUND_SUCCEEDED', 'REFUND_UNKNOWN')),
    CHECK (amount_fen > 0),
    CHECK (currency = 'CNY'),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='退款业务单';

CREATE TABLE refund_command_outbox (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    command_no VARCHAR(40) NOT NULL COMMENT '退款命令业务编号',
    refund_order_id BIGINT UNSIGNED NOT NULL COMMENT '退款单ID',
    command_status VARCHAR(16) NOT NULL COMMENT '状态：PENDING、SENT、DONE',
    payload_json JSON NOT NULL COMMENT '命令载荷',
    dispatched_at DATETIME NULL COMMENT '投递UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_refund_command_order (refund_order_id),
    UNIQUE KEY uk_refund_command_no (command_no),
    KEY idx_refund_command_status (command_status, gmt_created_time),
    CONSTRAINT fk_refund_command_refund FOREIGN KEY (refund_order_id) REFERENCES refund_order (id),
    CHECK (command_status IN ('PENDING', 'SENT', 'DONE')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='退款Provider命令发件箱';
