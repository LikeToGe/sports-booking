CREATE TABLE inventory_slot (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    store_id BIGINT UNSIGNED NOT NULL COMMENT '门店ID',
    schedule_version_id BIGINT UNSIGNED NOT NULL COMMENT '排期版本ID',
    source_type VARCHAR(16) NOT NULL COMMENT '来源：WEEKLY、SPECIAL',
    weekly_schedule_slot_id BIGINT UNSIGNED NULL COMMENT '周模板时段ID',
    special_date_slot_id BIGINT UNSIGNED NULL COMMENT '特殊日期时段ID',
    sellable_unit_version_id BIGINT UNSIGNED NOT NULL COMMENT '可售单元版本ID',
    inventory_date DATE NOT NULL COMMENT '库存日期，业务时区Asia/Shanghai',
    start_time TIME NOT NULL COMMENT '开始时间，业务时区',
    end_time TIME NOT NULL COMMENT '结束时间，业务时区',
    price_fen INT UNSIGNED NOT NULL COMMENT '整段总价，单位分',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_inventory_slot_weekly_date (weekly_schedule_slot_id, inventory_date),
    UNIQUE KEY uk_inventory_slot_special_date (special_date_slot_id, inventory_date),
    KEY idx_inventory_slot_store_date_time (store_id, inventory_date, start_time),
    CONSTRAINT fk_inventory_slot_store FOREIGN KEY (store_id) REFERENCES store (id),
    CONSTRAINT fk_inventory_slot_schedule_version FOREIGN KEY (schedule_version_id) REFERENCES schedule_version (id),
    CONSTRAINT fk_inventory_slot_weekly_schedule_slot FOREIGN KEY (weekly_schedule_slot_id) REFERENCES weekly_schedule_slot (id),
    CONSTRAINT fk_inventory_slot_special_date_slot FOREIGN KEY (special_date_slot_id) REFERENCES special_date_slot (id),
    CONSTRAINT fk_inventory_slot_sellable_unit_version FOREIGN KEY (sellable_unit_version_id) REFERENCES sellable_unit_version (id),
    CHECK (source_type IN ('WEEKLY', 'SPECIAL')),
    CHECK (start_time < end_time),
    CHECK (price_fen > 0),
    CHECK ((source_type = 'WEEKLY' AND weekly_schedule_slot_id IS NOT NULL AND special_date_slot_id IS NULL)
        OR (source_type = 'SPECIAL' AND weekly_schedule_slot_id IS NULL AND special_date_slot_id IS NOT NULL)),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='固定可售库存时段';

