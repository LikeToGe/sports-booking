CREATE TABLE schedule_version (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    store_id BIGINT UNSIGNED NOT NULL COMMENT '门店ID',
    version_no INT UNSIGNED NOT NULL COMMENT '版本号，从1递增',
    version_status VARCHAR(16) NOT NULL COMMENT '版本状态：DRAFT、PUBLISHED、RETIRED',
    effective_from DATE NOT NULL COMMENT '生效开始日期，业务时区Asia/Shanghai',
    effective_to DATE NULL COMMENT '生效结束日期，包含该日期',
    published_at DATETIME NULL COMMENT '发布时间，UTC',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_schedule_version_store_version_no (store_id, version_no),
    UNIQUE KEY uk_schedule_version_store_effective_from (store_id, effective_from),
    KEY idx_schedule_version_store_status_dates (store_id, version_status, effective_from, effective_to),
    CONSTRAINT fk_schedule_version_store FOREIGN KEY (store_id) REFERENCES store (id),
    CHECK (version_status IN ('DRAFT', 'PUBLISHED', 'RETIRED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='门店排期版本';

CREATE TABLE weekly_schedule_slot (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    schedule_version_id BIGINT UNSIGNED NOT NULL COMMENT '排期版本ID',
    week_day TINYINT UNSIGNED NOT NULL COMMENT '星期：1周一至7周日',
    sellable_unit_version_id BIGINT UNSIGNED NOT NULL COMMENT '可售单元版本ID',
    start_time TIME NOT NULL COMMENT '开始时间，业务时区',
    end_time TIME NOT NULL COMMENT '结束时间，业务时区',
    price_fen INT UNSIGNED NOT NULL COMMENT '整段总价，单位分',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    KEY idx_weekly_schedule_slot_version_day_time (schedule_version_id, week_day, start_time),
    CONSTRAINT fk_weekly_schedule_slot_version FOREIGN KEY (schedule_version_id) REFERENCES schedule_version (id),
    CONSTRAINT fk_weekly_schedule_slot_sellable_unit_version FOREIGN KEY (sellable_unit_version_id) REFERENCES sellable_unit_version (id),
    CHECK (week_day BETWEEN 1 AND 7),
    CHECK (start_time < end_time),
    CHECK (price_fen > 0),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='每周固定排期时段';

