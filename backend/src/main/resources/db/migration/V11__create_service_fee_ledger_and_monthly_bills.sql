CREATE TABLE monthly_bill (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    bill_no VARCHAR(40) NOT NULL COMMENT '账单业务编号',
    organization_id BIGINT UNSIGNED NOT NULL COMMENT '经营主体ID',
    store_id BIGINT UNSIGNED NOT NULL COMMENT '门店ID',
    billing_period DATE NOT NULL COMMENT '账期首日',
    accrual_fee_fen INT UNSIGNED NOT NULL DEFAULT '0' COMMENT '正向服务费分',
    adjustment_fee_fen INT NOT NULL DEFAULT '0' COMMENT '退款调整分',
    payable_fee_fen INT NOT NULL DEFAULT '0' COMMENT '应付服务费分',
    bill_status VARCHAR(16) NOT NULL COMMENT '账单状态：DRAFT、ISSUED、PAID、OVERDUE',
    issued_at DATETIME NULL COMMENT '出账UTC时间',
    due_date DATE NULL COMMENT '到期日期',
    paid_at DATETIME NULL COMMENT '支付UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_monthly_bill_store_period (store_id, billing_period),
    UNIQUE KEY uk_monthly_bill_no (bill_no),
    KEY idx_monthly_bill_organization_status_period (organization_id, bill_status, billing_period),
    CONSTRAINT fk_monthly_bill_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_monthly_bill_store FOREIGN KEY (store_id) REFERENCES store (id),
    CHECK (bill_status IN ('DRAFT', 'ISSUED', 'PAID', 'OVERDUE')),
    CHECK (billing_period = DATE_SUB(billing_period, INTERVAL DAY(billing_period) - 1 DAY)),
    CHECK (accrual_fee_fen >= 0),
    CHECK (payable_fee_fen >= 0),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='月服务费账单';

CREATE TABLE service_fee_ledger (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    entry_no VARCHAR(40) NOT NULL COMMENT '分录业务编号',
    organization_id BIGINT UNSIGNED NOT NULL COMMENT '经营主体ID',
    store_id BIGINT UNSIGNED NOT NULL COMMENT '门店ID',
    booking_order_id BIGINT UNSIGNED NOT NULL COMMENT '预约订单ID',
    monthly_bill_id BIGINT UNSIGNED NULL COMMENT '归集账单ID',
    source_type VARCHAR(24) NOT NULL COMMENT '来源：ORDER_COMPLETED、REFUND_ADJUSTMENT',
    source_id BIGINT UNSIGNED NOT NULL COMMENT '来源业务ID',
    entry_type VARCHAR(16) NOT NULL COMMENT '类型：ACCRUAL、ADJUSTMENT',
    billing_period DATE NOT NULL COMMENT '账期首日',
    base_amount_fen INT NOT NULL COMMENT '计费基数分，可为负调整',
    service_rate_basis_points INT UNSIGNED NOT NULL COMMENT '费率快照基点',
    fee_amount_fen INT NOT NULL COMMENT '服务费分，可为负调整',
    description VARCHAR(255) NOT NULL COMMENT '分录说明',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_service_fee_ledger_no (entry_no),
    UNIQUE KEY uk_service_fee_ledger_source (source_type, source_id),
    KEY idx_service_fee_ledger_store_period (store_id, billing_period, monthly_bill_id),
    KEY idx_service_fee_ledger_order (booking_order_id),
    CONSTRAINT fk_service_fee_ledger_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_service_fee_ledger_store FOREIGN KEY (store_id) REFERENCES store (id),
    CONSTRAINT fk_service_fee_ledger_order FOREIGN KEY (booking_order_id) REFERENCES booking_order (id),
    CONSTRAINT fk_service_fee_ledger_bill FOREIGN KEY (monthly_bill_id) REFERENCES monthly_bill (id),
    CHECK (source_type IN ('ORDER_COMPLETED', 'REFUND_ADJUSTMENT')),
    CHECK (entry_type IN ('ACCRUAL', 'ADJUSTMENT')),
    CHECK (billing_period = DATE_SUB(billing_period, INTERVAL DAY(billing_period) - 1 DAY)),
    CHECK (service_rate_basis_points <= 10000),
    CHECK ((entry_type = 'ACCRUAL' AND base_amount_fen > 0 AND fee_amount_fen >= 0) OR
           (entry_type = 'ADJUSTMENT' AND base_amount_fen < 0 AND fee_amount_fen <= 0)),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='不可变服务费分录';

CREATE TABLE bill_payment_record (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    payment_no VARCHAR(40) NOT NULL COMMENT '线下收款编号',
    monthly_bill_id BIGINT UNSIGNED NOT NULL COMMENT '月账单ID',
    payment_method VARCHAR(16) NOT NULL COMMENT '方式：OFFLINE',
    amount_fen INT UNSIGNED NOT NULL COMMENT '收款金额分',
    paid_at DATETIME NOT NULL COMMENT '收款UTC时间',
    remark VARCHAR(255) NULL COMMENT '收款备注',
    recorded_by_account_id BIGINT UNSIGNED NOT NULL COMMENT '记录平台管理员ID',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_bill_payment_record_no (payment_no),
    UNIQUE KEY uk_bill_payment_record_bill (monthly_bill_id),
    CONSTRAINT fk_bill_payment_record_bill FOREIGN KEY (monthly_bill_id) REFERENCES monthly_bill (id),
    CHECK (payment_method = 'OFFLINE'),
    CHECK (amount_fen > 0),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='账单线下收款记录';
