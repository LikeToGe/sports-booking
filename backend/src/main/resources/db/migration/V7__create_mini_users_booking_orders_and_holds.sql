CREATE TABLE mini_user (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    identity_provider VARCHAR(24) NOT NULL COMMENT '身份提供方：MOCK_WECHAT',
    provider_subject_hash CHAR(64) NOT NULL COMMENT '提供方用户标识哈希',
    status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、DISABLED',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_mini_user_provider_subject (identity_provider, provider_subject_hash),
    CHECK (identity_provider IN ('MOCK_WECHAT')),
    CHECK (status IN ('ACTIVE', 'DISABLED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='小程序用户';

CREATE TABLE mini_session (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    mini_user_id BIGINT UNSIGNED NOT NULL COMMENT '小程序用户ID',
    access_token_hash CHAR(64) NOT NULL COMMENT '访问令牌哈希',
    refresh_token_hash CHAR(64) NOT NULL COMMENT '刷新令牌哈希',
    access_expires_at DATETIME NOT NULL COMMENT '访问令牌到期UTC时间',
    refresh_expires_at DATETIME NOT NULL COMMENT '刷新令牌到期UTC时间',
    revoked_at DATETIME NULL COMMENT '撤销UTC时间',
    revoke_reason VARCHAR(32) NULL COMMENT '撤销原因',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_mini_session_access_token (access_token_hash),
    UNIQUE KEY uk_mini_session_refresh_token (refresh_token_hash),
    KEY idx_mini_session_user (mini_user_id),
    KEY idx_mini_session_refresh_expire (refresh_expires_at),
    CONSTRAINT fk_mini_session_user FOREIGN KEY (mini_user_id) REFERENCES mini_user (id),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='小程序访问与刷新会话';

CREATE TABLE mini_idempotency_record (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    mini_user_id BIGINT UNSIGNED NOT NULL COMMENT '小程序用户ID',
    request_scope VARCHAR(128) NOT NULL COMMENT '请求范围',
    idempotency_key VARCHAR(128) NOT NULL COMMENT '幂等键',
    request_hash CHAR(64) NOT NULL COMMENT '请求哈希',
    response_body JSON NOT NULL COMMENT '首次响应体',
    http_status SMALLINT UNSIGNED NOT NULL COMMENT '首次HTTP状态',
    expires_at DATETIME NOT NULL COMMENT '幂等窗口到期UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_mini_idempotency_user_scope_key (mini_user_id, request_scope, idempotency_key),
    KEY idx_mini_idempotency_expire (expires_at),
    CONSTRAINT fk_mini_idempotency_user FOREIGN KEY (mini_user_id) REFERENCES mini_user (id),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='小程序写请求幂等记录';

CREATE TABLE booking_order (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    order_no VARCHAR(40) NOT NULL COMMENT '订单业务编号',
    mini_user_id BIGINT UNSIGNED NOT NULL COMMENT '用户ID',
    organization_id BIGINT UNSIGNED NOT NULL COMMENT '经营主体ID快照',
    store_id BIGINT UNSIGNED NOT NULL COMMENT '门店ID快照',
    inventory_slot_id BIGINT UNSIGNED NOT NULL COMMENT '固定库存时段ID',
    schedule_version_id BIGINT UNSIGNED NOT NULL COMMENT '排期版本ID快照',
    sellable_unit_version_id BIGINT UNSIGNED NOT NULL COMMENT '可售单元版本ID快照',
    inventory_date DATE NOT NULL COMMENT '预约日期',
    start_time TIME NOT NULL COMMENT '预约开始时间',
    end_time TIME NOT NULL COMMENT '预约结束时间',
    price_fen INT UNSIGNED NOT NULL COMMENT '订单金额分',
    service_rate_basis_points INT UNSIGNED NOT NULL COMMENT '服务费率快照基点',
    contact_name VARCHAR(64) NOT NULL COMMENT '联系人姓名',
    contact_phone VARCHAR(32) NOT NULL COMMENT '联系人手机号',
    privacy_policy_version VARCHAR(64) NOT NULL COMMENT '隐私政策版本',
    privacy_consented_at DATETIME NOT NULL COMMENT '隐私同意UTC时间',
    privacy_consent_scene VARCHAR(64) NOT NULL COMMENT '隐私同意场景',
    order_status VARCHAR(24) NOT NULL COMMENT '订单状态',
    hold_expires_at DATETIME NOT NULL COMMENT '支付占用到期UTC时间',
    paid_at DATETIME NULL COMMENT '支付成功UTC时间',
    cancelled_at DATETIME NULL COMMENT '取消UTC时间',
    completed_at DATETIME NULL COMMENT '完成UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_booking_order_no (order_no),
    KEY idx_booking_order_user_status_time (mini_user_id, order_status, gmt_created_time),
    KEY idx_booking_order_store_status_date (store_id, order_status, inventory_date),
    KEY idx_booking_order_hold_expire (hold_expires_at, order_status),
    CONSTRAINT fk_booking_order_user FOREIGN KEY (mini_user_id) REFERENCES mini_user (id),
    CONSTRAINT fk_booking_order_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_booking_order_store FOREIGN KEY (store_id) REFERENCES store (id),
    CONSTRAINT fk_booking_order_inventory_slot FOREIGN KEY (inventory_slot_id) REFERENCES inventory_slot (id),
    CONSTRAINT fk_booking_order_schedule_version FOREIGN KEY (schedule_version_id) REFERENCES schedule_version (id),
    CONSTRAINT fk_booking_order_sellable_unit_version FOREIGN KEY (sellable_unit_version_id) REFERENCES sellable_unit_version (id),
    CHECK (order_status IN ('PENDING_PAYMENT', 'PAYMENT_PROCESSING', 'PAYMENT_UNKNOWN', 'CONFIRMED', 'CANCELLED', 'COMPLETED')),
    CHECK (price_fen > 0),
    CHECK (service_rate_basis_points <= 10000),
    CHECK (start_time < end_time),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='线上预约订单';

CREATE TABLE user_booking_quota (
    mini_user_id BIGINT UNSIGNED NOT NULL COMMENT '小程序用户ID',
    active_hold_count TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '当前支付占用数量',
    natural_expiry_count TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '冷却窗口内自然过期数量',
    natural_expiry_window_started_at DATETIME NULL COMMENT '自然过期窗口起始UTC时间',
    cooldown_until DATETIME NULL COMMENT '预约冷却截止UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (mini_user_id),
    CONSTRAINT fk_user_booking_quota_user FOREIGN KEY (mini_user_id) REFERENCES mini_user (id),
    CHECK (active_hold_count <= 2),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户预约占用配额';

CREATE TABLE booking_request_bucket (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    bucket_type VARCHAR(16) NOT NULL COMMENT '桶类型：DEVICE、SOURCE_IP',
    bucket_key_hash CHAR(64) NOT NULL COMMENT '设备或来源哈希',
    bucket_start_at DATETIME NOT NULL COMMENT '十分钟桶开始UTC时间',
    request_count TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '请求计数',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_booking_request_bucket (bucket_type, bucket_key_hash, bucket_start_at),
    CHECK (bucket_type IN ('DEVICE', 'SOURCE_IP')),
    CHECK (request_count <= 20),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='预约来源压力时间桶';

