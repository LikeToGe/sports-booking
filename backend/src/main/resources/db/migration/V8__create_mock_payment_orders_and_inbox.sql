CREATE TABLE payment_order (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    payment_no VARCHAR(40) NOT NULL COMMENT '支付业务编号',
    booking_order_id BIGINT UNSIGNED NOT NULL COMMENT '预约订单ID',
    provider VARCHAR(24) NOT NULL COMMENT '支付提供方：MOCK',
    provider_payment_no VARCHAR(64) NULL COMMENT 'Provider支付单号',
    amount_fen INT UNSIGNED NOT NULL COMMENT '支付金额分',
    currency VARCHAR(8) NOT NULL COMMENT '币种',
    payment_status VARCHAR(24) NOT NULL COMMENT '支付状态',
    provider_status VARCHAR(32) NULL COMMENT 'Provider原始状态',
    provider_result_at DATETIME NULL COMMENT 'Provider结果UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_payment_order_no (payment_no),
    UNIQUE KEY uk_payment_order_booking (booking_order_id),
    UNIQUE KEY uk_payment_order_provider_no (provider, provider_payment_no),
    KEY idx_payment_order_status_time (payment_status, gmt_modified_time),
    CONSTRAINT fk_payment_order_booking FOREIGN KEY (booking_order_id) REFERENCES booking_order (id),
    CHECK (provider IN ('MOCK')),
    CHECK (payment_status IN ('CREATED', 'PROCESSING', 'SUCCEEDED', 'FAILED', 'CLOSED', 'UNKNOWN')),
    CHECK (amount_fen > 0),
    CHECK (currency = 'CNY'),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='Mock支付单';

CREATE TABLE payment_event_inbox (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    provider VARCHAR(24) NOT NULL COMMENT '支付提供方：MOCK',
    provider_event_no VARCHAR(64) NOT NULL COMMENT 'Provider事件唯一编号',
    payment_order_id BIGINT UNSIGNED NOT NULL COMMENT '支付单ID',
    event_type VARCHAR(24) NOT NULL COMMENT '事件结果',
    payload_json JSON NOT NULL COMMENT '事件载荷',
    processed_at DATETIME NULL COMMENT '处理UTC时间',
    process_result VARCHAR(16) NOT NULL COMMENT '处理结果：PENDING、APPLIED、IGNORED、REJECTED',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_payment_event_provider_event (provider, provider_event_no),
    KEY idx_payment_event_payment_result (payment_order_id, process_result),
    CONSTRAINT fk_payment_event_payment FOREIGN KEY (payment_order_id) REFERENCES payment_order (id),
    CHECK (provider IN ('MOCK')),
    CHECK (event_type IN ('SUCCESS', 'FAILED', 'PROCESSING', 'UNKNOWN')),
    CHECK (process_result IN ('PENDING', 'APPLIED', 'IGNORED', 'REJECTED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='支付回调收件箱';

CREATE TABLE payment_command_outbox (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    command_no VARCHAR(40) NOT NULL COMMENT '命令业务编号',
    payment_order_id BIGINT UNSIGNED NOT NULL COMMENT '支付单ID',
    command_type VARCHAR(24) NOT NULL COMMENT '命令：CREATE、CLOSE',
    command_status VARCHAR(16) NOT NULL COMMENT '状态：PENDING、SENT、DONE',
    payload_json JSON NOT NULL COMMENT '命令载荷',
    dispatched_at DATETIME NULL COMMENT '投递UTC时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_payment_command_payment_type (payment_order_id, command_type),
    UNIQUE KEY uk_payment_command_no (command_no),
    KEY idx_payment_command_status (command_status, gmt_created_time),
    CONSTRAINT fk_payment_command_payment FOREIGN KEY (payment_order_id) REFERENCES payment_order (id),
    CHECK (command_type IN ('CREATE', 'CLOSE')),
    CHECK (command_status IN ('PENDING', 'SENT', 'DONE')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='支付Provider命令发件箱';
