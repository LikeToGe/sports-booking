CREATE TABLE organization (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    organization_no VARCHAR(32) NOT NULL COMMENT '经营主体业务编号',
    name VARCHAR(128) NOT NULL COMMENT '经营主体名称',
    status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、PAUSED',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_organization_no (organization_no),
    CHECK (status IN ('ACTIVE', 'PAUSED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='经营主体';

CREATE TABLE store (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    organization_id BIGINT UNSIGNED NOT NULL COMMENT '经营主体ID',
    store_no VARCHAR(32) NOT NULL COMMENT '门店业务编号',
    name VARCHAR(128) NOT NULL COMMENT '门店名称',
    status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、PAUSED',
    service_rate_basis_points INT UNSIGNED NOT NULL COMMENT '服务费率，单位基点',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_store_no (store_no),
    UNIQUE KEY uk_store_organization (organization_id),
    CONSTRAINT fk_store_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CHECK (status IN ('ACTIVE', 'PAUSED')),
    CHECK (service_rate_basis_points <= 10000),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='门店';

CREATE TABLE admin_account (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    username VARCHAR(64) NOT NULL COMMENT '登录名',
    password_hash VARCHAR(255) NOT NULL COMMENT '密码哈希',
    display_name VARCHAR(64) NOT NULL COMMENT '显示名称',
    role VARCHAR(24) NOT NULL COMMENT '角色：PLATFORM_ADMIN、VENUE_ADMIN',
    store_id BIGINT UNSIGNED NULL COMMENT '门店ID',
    status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE、DISABLED、LOCKED',
    effective_venue_admin_store_id BIGINT UNSIGNED GENERATED ALWAYS AS (
        CASE WHEN role = 'VENUE_ADMIN' AND status <> 'DISABLED' AND is_deleted = 0 THEN store_id ELSE NULL END
    ) STORED COMMENT '有效场馆管理员门店ID',
    force_password_change TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否强制修改密码：0否 1是',
    failed_login_count INT UNSIGNED NOT NULL DEFAULT '0' COMMENT '连续登录失败次数',
    locked_until DATETIME NULL COMMENT '锁定截止时间',
    last_login_at DATETIME NULL COMMENT '最近成功登录时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_admin_account_username (username),
    UNIQUE KEY uk_admin_account_effective_venue_store (effective_venue_admin_store_id),
    KEY idx_admin_account_store_id (store_id),
    CONSTRAINT fk_admin_account_store FOREIGN KEY (store_id) REFERENCES store (id),
    CHECK (role IN ('PLATFORM_ADMIN', 'VENUE_ADMIN')),
    CHECK (status IN ('ACTIVE', 'DISABLED', 'LOCKED')),
    CHECK ((role = 'PLATFORM_ADMIN' AND store_id IS NULL) OR (role = 'VENUE_ADMIN' AND store_id IS NOT NULL)),
    CHECK (force_password_change IN (0, 1)),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='管理端账号';

CREATE TABLE admin_session (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    account_id BIGINT UNSIGNED NOT NULL COMMENT '管理端账号ID',
    session_token_hash CHAR(64) NOT NULL COMMENT '会话令牌SHA-256哈希',
    csrf_token_hash CHAR(64) NOT NULL COMMENT 'CSRF令牌SHA-256哈希',
    expires_at DATETIME NOT NULL COMMENT '过期时间',
    revoked_at DATETIME NULL COMMENT '撤销时间',
    revoke_reason VARCHAR(32) NULL COMMENT '撤销原因',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_admin_session_token_hash (session_token_hash),
    KEY idx_admin_session_account_id (account_id),
    KEY idx_admin_session_expires_at (expires_at),
    CONSTRAINT fk_admin_session_account FOREIGN KEY (account_id) REFERENCES admin_account (id),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='管理端会话';

CREATE TABLE idempotency_record (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    account_id BIGINT UNSIGNED NOT NULL COMMENT '认证管理端账号ID',
    request_scope VARCHAR(128) NOT NULL COMMENT '请求范围',
    idempotency_key VARCHAR(128) NOT NULL COMMENT '幂等键',
    request_hash CHAR(64) NOT NULL COMMENT '规范化请求哈希',
    response_body JSON NOT NULL COMMENT '首次处理响应体',
    http_status SMALLINT UNSIGNED NOT NULL COMMENT '首次处理HTTP状态码',
    expires_at DATETIME NOT NULL COMMENT '幂等过期时间',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_idempotency_record_account_scope_key (account_id, request_scope, idempotency_key),
    KEY idx_idempotency_record_expires_at (expires_at),
    CONSTRAINT fk_idempotency_record_account FOREIGN KEY (account_id) REFERENCES admin_account (id),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='幂等记录';

CREATE TABLE audit_log (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    actor_account_id BIGINT UNSIGNED NULL COMMENT '发起账号ID',
    action VARCHAR(64) NOT NULL COMMENT '操作动作',
    target_type VARCHAR(32) NOT NULL COMMENT '目标类型',
    target_id BIGINT UNSIGNED NULL COMMENT '目标ID',
    organization_id BIGINT UNSIGNED NULL COMMENT '经营主体ID',
    store_id BIGINT UNSIGNED NULL COMMENT '门店ID',
    result VARCHAR(16) NOT NULL COMMENT '处理结果：SUCCEEDED、REJECTED、FAILED',
    reason VARCHAR(256) NULL COMMENT '原因',
    request_id VARCHAR(64) NULL COMMENT '请求关联ID',
    create_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建用户ID',
    modify_operator_id BIGINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '修改用户ID',
    gmt_created_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    gmt_modified_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否删除：0未删除 1已删除',
    PRIMARY KEY (id),
    KEY idx_audit_log_actor_account_id (actor_account_id),
    KEY idx_audit_log_target (target_type, target_id),
    KEY idx_audit_log_organization_store (organization_id, store_id),
    CHECK (result IN ('SUCCEEDED', 'REJECTED', 'FAILED')),
    CHECK (is_deleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='管理操作审计日志';
